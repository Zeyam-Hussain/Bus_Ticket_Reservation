-- Dynamic pricing schema upgrade for existing PostgreSQL databases.
BEGIN;

ALTER TABLE route
    ADD COLUMN IF NOT EXISTS min_fare NUMERIC(10, 2),
    ADD COLUMN IF NOT EXISTS max_fare NUMERIC(10, 2);

UPDATE route
SET min_fare = ROUND(base_fare * 0.80, 2),
    max_fare = ROUND(base_fare * 1.50, 2)
WHERE min_fare IS NULL OR max_fare IS NULL;

ALTER TABLE route
    ALTER COLUMN min_fare SET NOT NULL,
    ALTER COLUMN max_fare SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'route_fare_bounds_check'
    ) THEN
        ALTER TABLE route ADD CONSTRAINT route_fare_bounds_check
            CHECK (min_fare > 0 AND max_fare >= min_fare
                AND base_fare >= min_fare AND base_fare <= max_fare);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS pricing_settings (
    id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    mode VARCHAR(10) NOT NULL DEFAULT 'shadow'
        CHECK (mode IN ('off', 'shadow', 'live')),
    quote_ttl_minutes INTEGER NOT NULL DEFAULT 30
        CHECK (quote_ttl_minutes BETWEEN 5 AND 240),
    updated_by BIGINT REFERENCES users(user_id) ON DELETE SET NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
INSERT INTO pricing_settings (id) VALUES (1) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS pricing_recommendations (
    recommendation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
    model_version VARCHAR(50) NOT NULL,
    feature_snapshot JSONB NOT NULL,
    predicted_demand NUMERIC(5, 4) NOT NULL
        CHECK (predicted_demand BETWEEN 0 AND 1),
    base_fare NUMERIC(10, 2) NOT NULL CHECK (base_fare > 0),
    recommended_fare NUMERIC(10, 2) NOT NULL CHECK (recommended_fare > 0),
    min_fare NUMERIC(10, 2) NOT NULL CHECK (min_fare > 0),
    max_fare NUMERIC(10, 2) NOT NULL CHECK (max_fare >= min_fare),
    generated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (recommended_fare BETWEEN min_fare AND max_fare)
);
CREATE INDEX IF NOT EXISTS pricing_recommendations_route_time_idx
    ON pricing_recommendations (route_id, generated_at DESC);

CREATE TABLE IF NOT EXISTS fare_quotes (
    quote_id VARCHAR(32) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    route_id BIGINT NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
    recommendation_id BIGINT REFERENCES pricing_recommendations(recommendation_id)
        ON DELETE SET NULL,
    fare NUMERIC(10, 2) NOT NULL CHECK (fare > 0),
    expires_at TIMESTAMP NOT NULL,
    used_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS fare_quotes_active_user_route_idx
    ON fare_quotes (user_id, route_id) WHERE used_at IS NULL;
CREATE INDEX IF NOT EXISTS fare_quotes_expiry_idx
    ON fare_quotes (expires_at) WHERE used_at IS NULL;

ALTER TABLE booking
    ADD COLUMN IF NOT EXISTS fare_charged NUMERIC(10, 2),
    ADD COLUMN IF NOT EXISTS quote_id VARCHAR(32);

UPDATE booking b
SET fare_charged = COALESCE(
    (
        SELECT p.total_amount
        FROM payment p
        WHERE p.booking_id = b.booking_id
          AND p.transaction_status = 'completed'
        ORDER BY p.paid_at DESC, p.payment_id DESC
        LIMIT 1
    ),
    r.base_fare
)
FROM route r
WHERE r.route_id = b.route_id AND b.fare_charged IS NULL;

ALTER TABLE booking
    ALTER COLUMN fare_charged SET NOT NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'booking_fare_charged_check'
    ) THEN
        ALTER TABLE booking ADD CONSTRAINT booking_fare_charged_check
            CHECK (fare_charged > 0);
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'booking_quote_id_fkey'
    ) THEN
        ALTER TABLE booking ADD CONSTRAINT booking_quote_id_fkey
            FOREIGN KEY (quote_id) REFERENCES fare_quotes(quote_id) ON DELETE SET NULL;
    END IF;
END $$;

COMMIT;
