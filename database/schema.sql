-- Main PostgreSQL schema for the Bus Ticket Reservation System.

CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    phone VARCHAR(20),
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(20) NOT NULL DEFAULT 'passenger'
        CHECK (role IN ('admin', 'passenger')),
    otp_code VARCHAR(6),
    otp_expiry TIMESTAMP,
    otp_requests INTEGER NOT NULL DEFAULT 0,
    otp_last_request DATE,
    is_verified SMALLINT NOT NULL DEFAULT 0 CHECK (is_verified IN (0, 1)),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bus (
    bus_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_number VARCHAR(50) NOT NULL UNIQUE,
    bus_type VARCHAR(50) NOT NULL,
    total_capacity INTEGER NOT NULL CHECK (total_capacity > 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS route (
    route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id BIGINT NOT NULL REFERENCES bus(bus_id) ON DELETE CASCADE,
    source_city VARCHAR(100) NOT NULL,
    destination_city VARCHAR(100) NOT NULL,
    departure_time TIMESTAMP NOT NULL,
    arrival_time TIMESTAMP NOT NULL,
    base_fare NUMERIC(10, 2) NOT NULL CHECK (base_fare > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'inactive')),
    CHECK (arrival_time > departure_time)
);

CREATE TABLE IF NOT EXISTS seat (
    seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bus_id BIGINT NOT NULL REFERENCES bus(bus_id) ON DELETE CASCADE,
    seat_number VARCHAR(10) NOT NULL,
    seat_type VARCHAR(20) NOT NULL DEFAULT 'unassigned'
        CHECK (seat_type IN ('male', 'female', 'unassigned')),
    UNIQUE (bus_id, seat_number)
);

CREATE TABLE IF NOT EXISTS booking (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    route_id BIGINT NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
    seat_id BIGINT NOT NULL REFERENCES seat(seat_id) ON DELETE CASCADE,
    passenger_gender VARCHAR(10) NOT NULL
        CHECK (passenger_gender IN ('Male', 'Female')),
    booking_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    cancellation_date TIMESTAMP,
    booking_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (booking_status IN ('pending', 'confirmed', 'cancelled'))
);

CREATE UNIQUE INDEX IF NOT EXISTS booking_active_route_seat_unique
    ON booking (route_id, seat_id)
    WHERE booking_status IN ('pending', 'confirmed');

CREATE TABLE IF NOT EXISTS payment (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES booking(booking_id) ON DELETE CASCADE,
    total_amount NUMERIC(10, 2) NOT NULL CHECK (total_amount >= 0),
    payment_method VARCHAR(50) NOT NULL,
    transaction_status VARCHAR(20) NOT NULL DEFAULT 'pending'
        CHECK (transaction_status IN ('pending', 'completed', 'failed')),
    transaction_id VARCHAR(100) UNIQUE,
    paid_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS seat_locks (
    lock_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id BIGINT NOT NULL REFERENCES route(route_id) ON DELETE CASCADE,
    seat_id BIGINT NOT NULL REFERENCES seat(seat_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    gender VARCHAR(10) NOT NULL CHECK (gender IN ('Male', 'Female')),
    locked_until TIMESTAMP NOT NULL,
    UNIQUE (route_id, seat_id)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    token VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS token_blacklist (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jti VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMP NOT NULL
);

CREATE TABLE IF NOT EXISTS login_attempts (
    login_attempt_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ip_address VARCHAR(45) NOT NULL,
    email VARCHAR(255) NOT NULL,
    success SMALLINT NOT NULL DEFAULT 0 CHECK (success IN (0, 1)),
    attempted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS route_search_idx
    ON route (source_city, destination_city, departure_time);
CREATE INDEX IF NOT EXISTS booking_user_date_idx
    ON booking (user_id, booking_date DESC);
CREATE INDEX IF NOT EXISTS login_attempts_ip_time_idx
    ON login_attempts (ip_address, attempted_at DESC);

CREATE OR REPLACE VIEW active_routes_view AS
SELECT
    r.route_id,
    r.bus_id,
    b.registration_number,
    b.bus_type,
    r.source_city,
    r.destination_city,
    r.departure_time,
    r.arrival_time,
    r.base_fare,
    b.total_capacity,
    GREATEST(
        b.total_capacity - COUNT(book.booking_id)
            FILTER (WHERE book.booking_status IN ('pending', 'confirmed')),
        0
    ) AS available_seats
FROM route r
JOIN bus b ON b.bus_id = r.bus_id
LEFT JOIN booking book ON book.route_id = r.route_id
WHERE r.status = 'active'
  AND r.departure_time > CURRENT_TIMESTAMP
GROUP BY r.route_id, b.bus_id;

CREATE OR REPLACE VIEW revenue_by_route_view AS
SELECT
    r.route_id,
    r.source_city,
    r.destination_city,
    COUNT(DISTINCT b.booking_id) FILTER (
        WHERE b.booking_status = 'confirmed'
    ) AS total_bookings,
    COALESCE(SUM(p.total_amount) FILTER (
        WHERE p.transaction_status = 'completed'
    ), 0) AS total_revenue
FROM route r
LEFT JOIN booking b ON b.route_id = r.route_id
LEFT JOIN payment p ON p.booking_id = b.booking_id
GROUP BY r.route_id, r.source_city, r.destination_city;
